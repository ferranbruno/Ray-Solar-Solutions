const PRODUCTS_STORAGE_KEY = 'ray-solar-products';
import { apiRequest, getImageUrl } from './api';

export const products = [];

export const getProducts = () => {
  const storedProducts = window.localStorage.getItem(PRODUCTS_STORAGE_KEY);

  if (!storedProducts) {
    window.localStorage.setItem(PRODUCTS_STORAGE_KEY, JSON.stringify(products));
    return [];
  }

  try {
    return JSON.parse(storedProducts);
  } catch {
    window.localStorage.setItem(PRODUCTS_STORAGE_KEY, JSON.stringify(products));
    return [];
  }
};

export const saveProducts = (nextProducts) => {
  window.localStorage.setItem(PRODUCTS_STORAGE_KEY, JSON.stringify(nextProducts));
  return nextProducts;
};

export const getProductById = (id) => getProducts().find((product) => product.id === Number(id));

const FALLBACK_IMAGES = [
  'https://images.unsplash.com/photo-1509391366360-2e959784a276?auto=format&fit=crop&w=900&q=80',
  'https://images.unsplash.com/photo-1497440001374-f26997328c1b?auto=format&fit=crop&w=900&q=80',
  'https://images.unsplash.com/photo-1473341304170-971dccb5ac1e?auto=format&fit=crop&w=900&q=80',
  'https://images.unsplash.com/photo-1508514177221-188b1cf16e9d?auto=format&fit=crop&w=900&q=80',
];

const normalizeProduct = (product) => ({
  ...product,
  image: getImageUrl(product.image_path) || FALLBACK_IMAGES[product.id % FALLBACK_IMAGES.length],
  status: product.is_active ? 'Approved' : 'Flagged',
});

export const fetchProducts = async () => {
  const data = await apiRequest('/products?per_page=100');
  return data.products.map(normalizeProduct);
};

export const fetchAdminProducts = async () => {
  const data = await apiRequest('/admin/products?per_page=100');
  return data.products.map(normalizeProduct);
};

export const fetchProviderProducts = async () => {
  const currentUser = await apiRequest('/auth/me');
  const data = await apiRequest('/products?per_page=100');

  return data.products
    .filter((product) => product.provider_id === currentUser.user.id)
    .map(normalizeProduct);
};

export const fetchProductById = async (id) => {
  const data = await apiRequest(`/products/${id}`);
  return normalizeProduct(data.product);
};
